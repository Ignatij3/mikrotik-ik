#ifndef LIB_TIME_MACROS_HPP_
#define LIB_TIME_MACROS_HPP_

#define MILLISECOND 1                   //!< Represents a single millisecond.
#define SECOND      1000 * MILLISECOND  //!< Represents a single second in milliseconds.
#define MINUTE      60 * SECOND         //!< Represents a single minute in milliseconds.
#define HOUR        60 * MINUTE         //!< Represents a single hour in milliseconds.
#define DAY         24 * HOUR           //!< Represents a single day in milliseconds.

#endif                                  // LIB_TIME_MACROS_HPP_